import { Info } from 'lucide-react'
import CommitField from '../components/CommitField'
import { usePostSession } from '../session'
import type { PostInsights } from '../workflow'

const BLOCKS: { key: keyof PostInsights; title: string; sub: string; placeholder: string }[] = [
  { key: 'audience', title: 'Customer insights', sub: 'What you know about the people this post is for', placeholder: 'e.g. They order in bulk and care about delivery dates…' },
  { key: 'painPoints', title: 'Pain points / needs', sub: 'What is stopping them from acting today', placeholder: 'e.g. Slow quotes, uncertain stock…' },
  { key: 'angles', title: 'Content angles', sub: 'The angles or messages you want to try', placeholder: 'e.g. In stock now · Trade pricing · Fast delivery' },
  { key: 'proof', title: 'Proof points', sub: 'Facts, results or testimonials you can honestly use', placeholder: 'e.g. 200+ trade customers; delivered in 48 hours' },
  { key: 'notes', title: 'Other notes', sub: 'Competitors, timing, approvals, anything else', placeholder: 'Free notes for this post' },
]

export default function IntelligenceTab({ onNext, onBack }: { onNext: () => void; onBack: () => void }) {
  const s = usePostSession()
  const { brief, insights } = s.workflow
  const set = (key: keyof PostInsights, v: string) => s.setWorkflow(w => ({ ...w, insights: { ...w.insights, [key]: v } }))

  return (
    <div>
      <div className="pcv2-stage-head"><span className="pcv2-stage-num">2</span><span className="pcv2-stage-title">Intelligence</span></div>
      <p className="pcv2-stage-sub">Your research notes for this post</p>

      <div className="pcv2-source-note" role="note" data-testid="pcv2-intelligence-honesty" style={{ marginTop: 16, display: 'flex', gap: 8, alignItems: 'flex-start' }}>
        <Info size={14} style={{ marginTop: 2, flex: 'none' }} />
        <span>No automated analysis is connected to Post Creator. These notes are written by you and saved with the post; nothing here is generated by AI or taken from a model. The Strategic Intelligence and Positioning pages in Content Studio currently show demo data and are not used here.</span>
      </div>

      <div className="pcv2-grid-2" style={{ marginTop: 16 }}>
        <div className="pcv2-card" data-testid="pcv2-intelligence-brief">
          <h3 className="pcv2-card-title">From your brief</h3>
          <p className="pcv2-card-sub">Edit these in Brief</p>
          <div className="pcv2-readonly-row"><span className="pcv2-readonly-label">Goal</span><span className="pcv2-readonly-value">{brief.goal}</span></div>
          <div className="pcv2-readonly-row"><span className="pcv2-readonly-label">Audience</span><span className="pcv2-readonly-value">{brief.audience || 'Not set'}</span></div>
          <div className="pcv2-readonly-row"><span className="pcv2-readonly-label">Product / offer</span><span className="pcv2-readonly-value">{brief.product || 'Not set'}</span></div>
          <div className="pcv2-readonly-row"><span className="pcv2-readonly-label">Key message</span><span className="pcv2-readonly-value">{brief.keyMessage || 'Not set'}</span></div>
          <div className="pcv2-readonly-row"><span className="pcv2-readonly-label">Call to action</span><span className="pcv2-readonly-value">{brief.cta || 'Not set'}</span></div>
        </div>
        {BLOCKS.map(b => (
          <div key={b.key} className="pcv2-card">
            <h3 className="pcv2-card-title">{b.title}</h3>
            <p className="pcv2-card-sub">{b.sub}</p>
            <CommitField multiline rows={5} value={insights[b.key]} onCommit={v => set(b.key, v)} placeholder={b.placeholder} ariaLabel={b.title} testId={`pcv2-insight-${b.key}`} maxLength={2000} />
          </div>
        ))}
      </div>

      <div className="pcv2-footer-nav">
        <button type="button" className="pcv2-btn pcv2-btn-secondary" onClick={onBack}>← Brief</button>
        <button type="button" className="pcv2-btn pcv2-btn-primary" onClick={onNext} data-testid="pcv2-next">Next: References →</button>
      </div>
    </div>
  )
}
